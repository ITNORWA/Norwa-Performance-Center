function render_matrix(data) {
    let $grid = $('#risk-matrix-grid');
    $grid.empty();

    // 5x5 Grid (Impact 5->1 (Rows), Likelihood 1->5 (Cols))
    for (let impact = 5; impact >= 1; impact--) {
        for (let likelihood = 1; likelihood <= 5; likelihood++) {
            let key = `${likelihood}-${impact}`;
            let risks = data[key] || [];
            let count = risks.length;
            let score = likelihood * impact;

            let colorClass = get_cell_color(score);

            let $cell = $(`
                <div class="matrix-cell ${colorClass}" data-key="${key}">
                    <div class="cell-score">${score}</div>
                    ${count > 0 ? `<div class="risk-count">${count}</div>` : ''}
                </div>
            `);

            $cell.click(function () {
                $('.matrix-cell').removeClass('active');
                $(this).addClass('active');
                show_risks(risks, likelihood, impact);
            });

            $grid.append($cell);
        }
    }
}

function get_cell_color(score) {
    if (score >= 15) return 'cell-red';
    if (score >= 6) return 'cell-yellow';
    return 'cell-green';
}

function show_risks(risks, l, i) {
    let $panel = $('#risk-details-panel');
    $panel.empty().hide().fadeIn();

    $panel.append(`<h4>Risks at L:${l} x I:${i}</h4>`);

    if (risks.length === 0) {
        $panel.append('<div class="empty-state">No risks found for this probability/impact combination.</div>');
        return;
    }

    let html = '<div class="list-group">';
    risks.forEach(risk => {
        html += `
            <a href="/app/risk-register/${risk.name}" class="list-group-item list-group-item-action">
                <div class="d-flex w-100 justify-content-between">
                    <h5 class="mb-1" style="font-weight: 700; color: #2d3748;">${risk.risk_title}</h5>
                    <span class="badge ${risk.risk_level === 'High' ? 'badge-red' : (risk.risk_level === 'Medium' ? 'badge-yellow' : 'badge-green')}">${risk.risk_level}</span>
                </div>
                <p class="mb-1 text-muted small">${risk.risk_category || 'General'} | Owner: ${risk.risk_owner || 'Unassigned'}</p>
                <small class="text-primary">ID: ${risk.name}</small>
            </a>
        `;
    });
    html += '</div>';

    $panel.append(html);
}

function bind_sidebar(page) {
    const $body = $(page.body);
    $body.find(".sidebar-menu li").on("click", function () {
        const section = $(this).data("section");
        if (section === "home") {
            frappe.set_route("performance-dashboard");
        } else if (section === "risk-management") {
            frappe.set_route("risk-dashboard");
        } else if (section === "administration") {
            frappe.set_route("Form", "Performance Settings");
        } else {
            frappe.set_route("performance-dashboard");
        }
    });
}
