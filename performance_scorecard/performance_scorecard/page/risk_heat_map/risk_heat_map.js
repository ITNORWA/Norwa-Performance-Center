frappe.pages['risk-heat-map'].on_page_load = function (wrapper) {
    var page = frappe.ui.make_app_page({
        parent: wrapper,
        title: 'Risk Heat Map',
        single_column: true
    });

    page.set_primary_action('Refresh', function () {
        load_heat_map(page);
    });

    // Add CSS
    frappe.require([
        '/assets/performance_scorecard/css/performance_dashboard.css',
        '/assets/performance_scorecard/css/risk_heat_map.css'
    ], () => {
        load_heat_map(page);
    });
}

function load_heat_map(page) {
    $(page.body).empty();
    $(page.body).append('<div class="dashboard-content">Loading...</div>');

    frappe.call({
        method: "performance_scorecard.performance_scorecard.page.risk_heat_map.risk_heat_map.get_risk_matrix_data",
        callback: function (r) {
            if (r.message) {
                render_page(page, r.message);
            }
        }
    });
}

